// --- Deterministic daily engine ---------------------------------------------
// Everyone worldwide sees the same phrase on the same calendar day, with no
// server: days-since-epoch, modulo phrase count. Uses LOCAL date (the card is
// "today" wherever the user is), date-only so time zones never split a day.

function dayNumber(date = new Date(), epoch = EPOCH) {
  const toMidnight = (d) => Date.UTC(d.getFullYear(), d.getMonth(), d.getDate());
  const [ey, em, ed] = epoch.split('-').map(Number);
  const epochMs = Date.UTC(ey, em - 1, ed);
  return Math.floor((toMidnight(date) - epochMs) / 86400000);
}

// Index into PHRASES for a given date. Negative days (before launch) wrap too,
// so the app still shows something sensible if opened "early".
export function indexForDate(date = new Date()) {
  const n = dayNumber(date);
  const len = PHRASES.length;
  return ((n % len) + len) % len;
}

export function phraseForDate(date = new Date()) {
  return PHRASES[indexForDate(date)];
}

// True if `date` is a Sunday — the weekly spotlight slot. The app builds a
// 5-phrase themed set client-side from the surrounding rotation; flagged here
// so the engine and UI agree on which days are special.
export function isSpotlight(date = new Date()) {
  return date.getDay() === 0;
}

// YYYY-MM-DD key for a date, used for archive ids and streak comparison.
export function dateKey(date = new Date()) {
  const p = (n) => String(n).padStart(2, '0');
  return `${date.getFullYear()}-${p(date.getMonth() + 1)}-${p(date.getDate())}`;
}
